import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(`${process.env.UI_CAPTURE_DIR}/node_modules/playwright/index.mjs`);
const output = fileURLToPath(new URL('.', import.meta.url));
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, colorScheme: 'dark' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
const check = async (condition, message) => { assert(await condition, message); };
const shot = async (name) => page.screenshot({ path: `${output}${name}.png` });
for (const type of ['books', 'movies', 'games', 'musics']) {
  const result = await (await fetch(`http://127.0.0.1:5100/${type}/pagedsearch?searchText=&orderBy=title:asc&page=1&pageSize=75`)).json();
  const first = result.items[0];
  const direct = `http://127.0.0.1:3100/${type}?searchText=Fixture&orderBy=title:desc&page=2`;
  const ssr = await fetch(direct);
  assert.equal(ssr.status, 200);
  assert((await ssr.text()).includes(`${first.type} Fixture`), `${type} SSR includes API-loaded records`);
  await page.goto(direct, { waitUntil: 'networkidle' });
  await check(page.getByRole('searchbox').inputValue().then((value) => value === 'Fixture'), 'search hydrated');
  assert.equal(await page.getByLabel('Select page').inputValue(), '2');
  await page.getByRole('searchbox').fill('Fixture');
  await page.getByRole('searchbox').press('Enter');
  await page.waitForURL((url) => !url.searchParams.has('page'));
  assert.equal(await page.getByRole('searchbox').evaluate((element) => element === document.activeElement), true);
  assert.equal(new URL(page.url()).searchParams.get('orderBy'), 'title:desc');
  await page.getByRole('link', { name: 'Title', exact: true }).click();
  await page.waitForURL((url) => url.searchParams.get('orderBy') === 'title:asc');
  assert.equal(new URL(page.url()).searchParams.get('searchText'), 'Fixture');
  await page.getByRole('link', { name: 'Next', exact: true }).click();
  await page.waitForURL((url) => url.searchParams.get('page') === '2');
  await page.waitForFunction(() => document.querySelector('select[aria-label="Select page"]')?.value === '2');
  const listUrl = page.url();
  const detail = page.locator('table tbody a').first();
  const title = (await detail.textContent()).split(': A collection fixture')[0];
  await detail.click();
  await page.waitForURL((url) => url.pathname.split('/').length === 3);
  await page.getByRole('heading', { name: title, exact: true }).waitFor();
  const detailUrl = page.url();
  assert.equal(await page.locator('#main-content').evaluate((element) => element === document.activeElement), true);
  assert.equal(new URL(page.url()).searchParams.get('page'), '2');
  await page.goBack({ waitUntil: 'networkidle' });
  assert.equal(page.url(), listUrl);
  await page.goForward({ waitUntil: 'networkidle' });
  assert.equal(page.url(), detailUrl);
  await page.getByRole('heading', { name: title, exact: true }).waitFor();
  await page.getByRole('link', { name: `Back to ${first.type}` }).click();
  await page.waitForURL(listUrl);
  await page.getByRole('link', { name: 'Clear search' }).click();
  await page.waitForURL((url) => !url.searchParams.has('searchText'));
  await page.goto(`http://127.0.0.1:3100/${type}/${first.id}`, { waitUntil: 'networkidle' });
  const detailHtml = await (await fetch(page.url())).text();
  assert(detailHtml.includes(first.title), `${type} detail SSR`);
  const image = page.locator('main img').first();
  assert((await image.getAttribute('src')).startsWith('/dev-api/static/images/'));
  assert.equal(await image.evaluate((element) => element.complete && element.naturalWidth > 0), true);
  await shot(`${type}-detail`);
  await page.getByRole('button', { name: /View full size/ }).click();
  await check(page.getByRole('dialog').isVisible(), 'image dialog opens');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await check(page.getByRole('button', { name: /View full size/ }).evaluate((element) => element === document.activeElement), 'image dialog restores trigger focus');
  await page.goto(`http://127.0.0.1:3100/${type}`, { waitUntil: 'networkidle' });
  await shot(`${type}-list`);
  console.log(`${type}: SSR, hydration, search/order/page, detail, back/forward, image and keyboard passed`);
}
// A delayed real loader response exposes pending state; submitting the same query revalidates.
let dataRequests = 0;
await page.route('**/books.data*', async (route) => {
  dataRequests++;
  const response = await route.fetch();
  await new Promise((resolve) => setTimeout(resolve, 600));
  await route.fulfill({ response });
});
await page.goto('http://127.0.0.1:3100/books', { waitUntil: 'networkidle' });
await page.getByRole('searchbox').fill('Fixture');
await page.getByRole('button', { name: 'Search', exact: true }).click();
await page.getByRole('status', { name: 'Loading collection' }).waitFor();
await page.getByRole('status', { name: 'Loading collection' }).waitFor({ state: 'detached' });
await page.getByRole('button', { name: 'Search', exact: true }).click();
await page.getByRole('status', { name: 'Loading collection' }).waitFor();
await page.getByRole('status', { name: 'Loading collection' }).waitFor({ state: 'detached' });
assert(dataRequests >= 2);
await page.unroute('**/books.data*');
await page.setViewportSize({ width: 390, height: 844 });
await shot('books-mobile');
await page.goto('http://127.0.0.1:3001/books?searchText=Fixture&orderBy=title:asc', { waitUntil: 'networkidle' });
await shot('baseline-books-mobile');
await page.setViewportSize({ width: 1280, height: 800 });
await shot('baseline-books-list');
await page.locator('table tbody a').first().click();
await page.waitForLoadState('networkidle');
await shot('baseline-books-detail');
assert.deepEqual(errors, [], 'No normal-page hydration, console or page errors');
for (const url of ['/unknown', '/Books', '/constructor', `/books/${'f'.repeat(24)}`, '/books/not-an-id']) {
  const response = await fetch(`http://127.0.0.1:3100${url}`);
  assert.equal(response.status, 404, url);
  assert((await response.text()).includes('Media not found'));
}
console.log('Pending/revalidation, mobile/baseline screens, invalid collection and missing-record statuses passed. No normal-page console/page errors.');
const productionRecords = await (await fetch('http://127.0.0.1:5100/Books/pagedsearch?searchText=&orderBy=title:asc&page=1&pageSize=75')).json();
await page.goto(`http://127.0.0.1:3101/books/${productionRecords.items[0].id}`, { waitUntil: 'networkidle' });
assert((await page.locator('main img').getAttribute('src')).startsWith('http://127.0.0.1:5100/static/images/'));
assert.equal(await page.locator('main img').evaluate((element) => element.complete && element.naturalWidth > 0), true);
const failureResponse = await page.goto('http://127.0.0.1:3102/books', { waitUntil: 'networkidle' });
assert.equal(failureResponse.status(), 503);
assert(await page.getByRole('button', { name: 'Try again' }).isVisible());
assert(!(await page.locator('body').innerText()).includes('5199'));
await shot('api-unavailable');
console.log('Built production detail with separate public image origin and sanitized real unreachable-API503 passed.');
await browser.close();
